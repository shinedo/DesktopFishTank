using System.Collections.Generic;
using System.Windows.Media;

namespace DesktopFish.Rendering;

/// <summary>
/// 荧光玻璃鱼的配色库。强调色决定体侧荧光带，副强调色决定体后暖斑与内脏色，
/// 体壁本身几乎不着色，所以换色就是换“发什么光”。
/// </summary>
public static class FishPaletteCatalog
{
    public static IReadOnlyList<FishPalette> All { get; } = new[]
    {
        FishPalette.Create(C(0x3A, 0xFF, 0xD2), C(0xFF, 0x4D, 0x5E)),   // 青绿
        FishPalette.Create(C(0x5A, 0xD8, 0xFF), C(0xFF, 0x8A, 0x3D)),   // 冰蓝
        FishPalette.Create(C(0x9B, 0x8C, 0xFF), C(0xFF, 0x4F, 0xD8)),   // 紫青
        FishPalette.Create(C(0xB6, 0xFF, 0x57), C(0x38, 0xC8, 0xFF)),   // 荧光黄绿
        FishPalette.Create(C(0xFF, 0x4F, 0x7A), C(0x6C, 0xFF, 0xD8)),   // 玫红
        FishPalette.Create(C(0xFF, 0xB3, 0x47), C(0x3A, 0xE0, 0xFF)),   // 琥珀
        FishPalette.Create(C(0x3D, 0xFF, 0xB0), C(0x7B, 0x5C, 0xFF)),   // 极光
        FishPalette.Create(C(0x3D, 0x9B, 0xFF), C(0xB6, 0xFF, 0x57)),   // 深海
        FishPalette.Create(C(0xFF, 0x7A, 0xD9), C(0x5A, 0xE0, 0xFF)),   // 樱粉
        FishPalette.Create(C(0xC8, 0xFF, 0x3D), C(0xFF, 0x3D, 0x8A)),   // 青柠
        FishPalette.Create(C(0xC7, 0x7B, 0xFF), C(0x4D, 0xFF, 0xC4)),   // 紫罗兰
        FishPalette.Create(C(0x9F, 0xE8, 0xFF), C(0xFF, 0xC2, 0x4D)),   // 白青
    };

    public static FishPalette Default => All[0];

    private static Color C(byte r, byte g, byte b) => Color.FromRgb(r, g, b);
}
